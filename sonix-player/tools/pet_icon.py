#!/usr/bin/env python3
"""Draws the pet's own glyph into src/gui/pet/peticon.c.

The More menu's glyphs are generated from assets/icons by tools/svg_to_lvgl.py,
which needs cairo and rewrites the 26 MB icons.c for a single new picture. The
pet is one 32 px shape, so it is drawn here instead and written to its own small
file: same ARGB8888 white-with-alpha form as the rest of the icon set, so the
theme tints it with lv_obj_set_style_image_recolor() like every other glyph.

    pip install pillow
    python3 tools/pet_icon.py

The output is checked in; building the player needs neither Python nor Pillow.
"""

import os

from PIL import Image, ImageDraw

SUPERSAMPLE = 8
SIZE = 112
OUT_C = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "gui", "pet", "peticon.c")
OUT_H = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "gui", "pet", "peticon.h")


def glyph():
    s = SIZE * SUPERSAMPLE
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)

    def box(x0, y0, x1, y1):
        return [x0 * s / 32, y0 * s / 32, x1 * s / 32, y1 * s / 32]

    white = (255, 255, 255, 255)

    # The two ears, drawn first so the body's shoulders cover their bottoms.
    draw.ellipse(box(5.2, 4.4, 13.2, 13.6), fill=white)
    draw.ellipse(box(18.8, 4.4, 26.8, 13.6), fill=white)

    # The body: an egg with the wide end at the bottom, the way every pocket
    # creature is drawn.
    draw.ellipse(box(4.4, 8.4, 27.6, 28.4), fill=white)

    # Feet, cut out of the body rather than added to it: the silhouette stays
    # one shape, which is what reads at 32 px.
    draw.ellipse(box(7.4, 24.6, 13.4, 29.4), fill=(0, 0, 0, 0))
    draw.ellipse(box(18.6, 24.6, 24.6, 29.4), fill=(0, 0, 0, 0))
    draw.rectangle(box(12.4, 25.4, 19.6, 29.4), fill=(0, 0, 0, 0))

    # Eyes, and the little open mouth between them.
    draw.ellipse(box(10.4, 15.2, 14.4, 19.8), fill=(0, 0, 0, 0))
    draw.ellipse(box(17.6, 15.2, 21.6, 19.8), fill=(0, 0, 0, 0))
    draw.ellipse(box(14.1, 20.4, 17.9, 23.4), fill=(0, 0, 0, 0))

    return img.resize((SIZE, SIZE), Image.LANCZOS)


def emit():
    img = glyph()
    pixels = img.load()
    data = bytearray()
    for y in range(SIZE):
        for x in range(SIZE):
            r, g, b, a = pixels[x, y]
            assert r == g == b, "the glyph is one colour"
            data += bytes((b, g, r, a))

    lines = []
    lines.append("/*")
    lines.append(" * GENERATED FILE -- do not edit by hand.")
    lines.append(" * Produced by tools/pet_icon.py. White ARGB8888, tinted by the theme.")
    lines.append(" */")
    lines.append("")
    lines.append('#include "peticon.h"')
    lines.append("")
    lines.append("// The pet's own glyph, 112x112: an egg-shaped creature with two ears and a")
    lines.append("// face cut out of the silhouette.")
    lines.append("static const uint8_t pet_icon_data[] = {")
    for i in range(0, len(data), 16):
        chunk = ", ".join("0x%02x" % b for b in data[i : i + 16])
        lines.append("\t" + chunk + ",")
    lines.append("};")
    lines.append("")
    lines.append("const lv_image_dsc_t icon_pet = {")
    lines.append("\t.header = {")
    lines.append("\t\t.magic = LV_IMAGE_HEADER_MAGIC,")
    lines.append("\t\t.cf = LV_COLOR_FORMAT_ARGB8888,")
    lines.append("\t\t.w = %d," % SIZE)
    lines.append("\t\t.h = %d," % SIZE)
    lines.append("\t\t.stride = %d," % (SIZE * 4))
    lines.append("\t},")
    lines.append("\t.data_size = sizeof(pet_icon_data),")
    lines.append("\t.data = pet_icon_data,")
    lines.append("};")
    lines.append("")

    with open(OUT_C, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    with open(OUT_H, "w", encoding="utf-8") as f:
        f.write(
            "#ifndef GUI_PET_PETICON_H\n"
            "#define GUI_PET_PETICON_H\n"
            "\n"
            '#include "lvgl/lvgl.h"\n'
            "\n"
            "// Generated by tools/pet_icon.py; see the comment there.\n"
            "extern const lv_image_dsc_t icon_pet;\n"
            "\n"
            "#endif /* GUI_PET_PETICON_H */\n"
        )


if __name__ == "__main__":
    emit()
