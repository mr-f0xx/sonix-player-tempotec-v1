#!/usr/bin/env python3
"""Generate the three Spotify marks the player carries, at their native size.

    python3 tools/make_spotify_icons.py

Writes src/gui/shell/spotify_icons.c, which the build compiles like icons.c --
so building the player needs no Python, no SVG renderer and no network, which
is the rule every generated asset here follows (see tools/main_menu_icons.py).

The shapes are Spotify's own mark drawn from its geometry rather than rendered
from their file: a filled circle, and three arcs that bow upward, each wider
and a little lower than the one above it. A8 keeps the alpha and lets LVGL
recolour the glyph through theme_style_icon, so one asset serves the tile, the
Now Playing badge and every palette including OLED's white.

Three names, one drawing, at 32x32:
  icon_spotify_mark   the Streaming grid's tile glyph and the Now Playing badge
  icon_spotify_menu   the Tokyo Night list row's glyph, which sits at 22 px and
                      wants the same picture, not a second drawing of it
  icon_spotify_badge  the badge, kept separate so a later theme can give it its
                      own treatment without touching the tile
"""

from pathlib import Path

SIZE = 32
ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src" / "gui" / "shell" / "spotify_icons.c"


def circle_alpha(x, y, cx, cy, r):
    d = ((x + 0.5 - cx) ** 2 + (y + 0.5 - cy) ** 2) ** 0.5
    return max(0.0, min(1.0, r + 0.5 - d))


def bar_alpha(x, y, bow_cx, cy, radius, thickness, span_px=None):
    """One bow, as the thick top of a circle centred far below the glyph.

    A rectangle `span_px` wide centred on the glyph, intersected with a band
    `thickness` wide around that circle -- which is how the mark's three bars
    are drawn: widest at the top, each one a little flatter than the last.
    """
    import math

    if span_px is None:
        span_px = radius * 1.45
    if abs(x + 0.5 - bow_cx) > span_px / 2.0:
        return 0.0
    # Only the top of the circle: a bottom half would be a second bar.
    if y + 0.5 > cy:
        return 0.0
    d = math.hypot(x + 0.5 - bow_cx, y + 0.5 - cy)
    miss = abs(d - radius)
    half = thickness / 2.0
    if miss >= half:
        return 0.0
    return 1.0 - (miss / half)


def glyph():
    rows = []
    for y in range(SIZE):
        row = []
        for x in range(SIZE):
            a = circle_alpha(x, y, SIZE / 2.0, SIZE / 2.0, SIZE / 2.0 - 0.7)
            # The bows: arcs whose centres sit under the mark, so each one
            # bends upward. Shorter and nearer the middle as they go down.
            for radius, thickness, drop, span in (
                (16.0, 3.0, 8.0, 22.0),
                (11.0, 3.0, 7.0, 15.0),
                (7.0, 3.2, 5.0, 9.0),
            ):
                cut = bar_alpha(x, y, SIZE / 2.0, SIZE - drop, radius, thickness, span)
                a = min(a, 1.0 - cut)
            row.append(int(round(max(0.0, a) * 255)))
        rows.append(row)
    return rows


def emit(name, rows):
    data = []
    for row in rows:
        data.extend(row)
    out = [f"static const uint8_t {name}_data[] = {{"]
    line = "\t"
    for i, v in enumerate(data):
        piece = f"0x{v:02x}, "
        if len(line) + len(piece) > 96:
            out.append(line.rstrip())
            line = "\t"
        line += piece
    if line.strip():
        out.append(line.rstrip())
    out.append("};")
    out.append("")
    out.append(f"const lv_image_dsc_t {name} = {{")
    out.append("\t.header = {")
    out.append("\t\t.magic = LV_IMAGE_HEADER_MAGIC,")
    out.append("\t\t.cf = LV_COLOR_FORMAT_A8,")
    out.append(f"\t\t.w = {SIZE},")
    out.append(f"\t\t.h = {SIZE},")
    out.append(f"\t\t.stride = {SIZE},")
    out.append("\t},")
    out.append(f"\t.data_size = sizeof({name}_data),")
    out.append(f"\t.data = {name}_data,")
    out.append("};")
    out.append("")
    return "\n".join(out)


def main():
    rows = glyph()
    parts = [
        "/* Generated by tools/make_spotify_icons.py -- do not edit by hand.",
        " *",
        " * LVGL 9 image descriptors, A8: alpha only, recoloured at runtime by",
        " * theme_style_icon. Three names, one drawing, so the badge can be given",
        " * its own treatment later without touching the menu's glyph. */",
        "",
        '#include "lvgl/lvgl.h"',
        "",
        emit("icon_spotify_mark", rows),
        emit("icon_spotify_menu", rows),
        emit("icon_spotify_badge", rows),
    ]
    OUTPUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
