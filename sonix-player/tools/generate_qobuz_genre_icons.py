#!/usr/bin/env python3
"""Generate the small white LVGL genre glyphs. Requires resvg-py and Pillow.

    python3 -m pip install resvg-py Pillow
    python3 tools/generate_qobuz_genre_icons.py
"""
from pathlib import Path
from io import BytesIO
from PIL import Image
from resvg_py import svg_to_bytes

root = Path(__file__).resolve().parent.parent
icons = sorted((root / "assets/icons/qobuz-genres").glob("*.svg"))
out = root / "src/gui/streaming/qobuzgenre_icons.c"
header = root / "src/gui/streaming/qobuzgenre_icons.h"
chunks = ['/* Generated by tools/generate_qobuz_genre_icons.py. */\n#include "qobuzgenre_icons.h"\n']
decls = []
for icon in icons:
    name = icon.stem
    image = Image.open(BytesIO(svg_to_bytes(svg_path=str(icon), width=32, height=32))).convert("RGBA")
    data = bytearray()
    for _, _, _, alpha in image.getdata():
        data.extend((255, 255, 255, alpha))
    lines = ["\t" + ", ".join(f"0x{x:02x}" for x in data[i:i+12]) + "," for i in range(0, len(data), 12)]
    chunks.append(f"static const uint8_t {name}_data[] = {{\n" + "\n".join(lines) + "\n};\n" +
        f"const lv_image_dsc_t qobuz_genre_{name} = {{\n"
        f"\t.header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888, .w = 32, .h = 32, .stride = 128}},\n"
        f"\t.data_size = sizeof({name}_data), .data = {name}_data,\n}};\n")
    decls.append(f"extern const lv_image_dsc_t qobuz_genre_{name};")
out.write_text("\n".join(chunks))
header.write_text("/* Generated by tools/generate_qobuz_genre_icons.py. */\n#ifndef QOBUZGENRE_ICONS_H\n#define QOBUZGENRE_ICONS_H\n#include <stdint.h>\n#include \"lvgl/lvgl.h\"\n" + "\n".join(decls) + "\n#endif\n")
