#!/usr/bin/env python3
"""Generates src/system/library/jisx0208.c, the JIS X 0208 table.

ID3v1 tags and ID3v2 frames written with encoding 0x00 have no way to say
"Japanese". Taggers on Japanese Windows wrote Shift-JIS and left the byte
alone, and so did older versions of the taggers on other systems. The bytes
then read as Latin-1: "宇多田ヒカル" comes out as "F½c q J", and the artist
is filed under F.

Shift-JIS and EUC-JP are two ways of addressing one character set: JIS X 0208,
94 rows of 94 cells. This tool writes that grid once, as a UTF-8 string pool
and one 16-bit offset per cell, so a reader needs a single lookup for either
encoding -- 0 meaning "no character in that cell".

    python3 tools/gen_jis_table.py            # writes the C file
    python3 tools/gen_jis_table.py --check    # exits 1 if it is out of date

The grid comes from Python's own EUC-JP codec: EUC-JP is the raw JIS X 0208
grid with 0x80 added to both bytes, so row r and cell c are the two bytes
(r + 0x80, c + 0x80). Shift-JIS is mapped onto the same grid with the standard
row/cell arithmetic (see jis_row_cell() in metadata.c), which the --check run
verifies against the CP932 codec for every pair.
"""

import argparse
import sys

HEADER = """\
// Generated by tools/gen_jis_table.py -- do not edit.
//
// JIS X 0208: the 94 x 94 grid that Shift-JIS and EUC-JP both address, with
// one UTF-8 string per character. JIS_ROW 0x21..0x7E, JIS_CELL 0x21..0x7E;
// a zero in JIS_OFFSETS means the code point has no character (the few empty
// cells of the standard, and the rows the standard never filled).
//
// Each cell's character is the NUL-terminated UTF-8 string at
// JIS_POOL + JIS_OFFSETS[(row - 0x21) * 94 + (cell - 0x21)]; an offset of
// zero in JIS_OFFSETS means the cell has no character.

#include "jisx0208.h"

// Every character, back to back, each NUL-terminated.
const unsigned char JIS_POOL[] = {
"""


def build_grid():
    """(row, cell) -> character, for every cell the EUC-JP codec knows."""
    grid = {}
    for row in range(0x21, 0x7F):
        for cell in range(0x21, 0x7F):
            try:
                text = bytes([row + 0x80, cell + 0x80]).decode("euc_jp")
            except UnicodeDecodeError:
                continue
            if len(text) == 1 and ord(text) < 0x10000:
                grid[(row, cell)] = text
    return grid


def render(grid):
    pool = bytearray()
    offsets = []
    for row in range(0x21, 0x7F):
        for cell in range(0x21, 0x7F):
            text = grid.get((row, cell))
            if text is None:
                offsets.append(0)
                continue
            offsets.append(len(pool))
            pool += text.encode("utf-8") + b"\0"

    # One byte per line's item, wrapped at 12 to a line.  Numeric initializers
    # (not a string literal) so the pool can hold NULs with no escaping, and
    # a 0 means "no character".
    lines = [HEADER]
    line = "\t"
    for byte in pool:
        piece = "%d," % byte
        if len(line) + len(piece) > 100:
            lines.append(line + "\n")
            line = "\t"
        line += piece
    if line.strip():
        lines.append(line + "\n")
    lines.append("};\n\n")

    used = [offset for offset in offsets if offset]
    lines.append("// One entry per cell of the grid, row 0x21 first.\n")
    lines.append("const uint16_t JIS_OFFSETS[JIS_GRID_CELLS] = {\n")
    for index in range(0, len(offsets), 12):
        chunk = offsets[index:index + 12]
        lines.append("\t" + ", ".join("%d" % value for value in chunk) + ",\n")
    lines.append("};\n")
    return "".join(lines), len(used), len(pool)


# The handful of cells where Windows CP932 and the JIS X 0208 standard draw a
# different glyph for the same cell. A tag written on Windows carries the
# CP932 shape; the standard one is what every other platform shows. The grid
# keeps the standard's, and the check accepts either: six cells of 6 879.
GLYPH_VARIANTS = {
    (0x21, 0x41): "\uff5e",  # wave dash
    (0x21, 0x42): "\u2225",  # double vertical line
    (0x21, 0x5D): "\uff0d",  # minus sign
    (0x21, 0x71): "\uffe0",  # cent sign
    (0x21, 0x72): "\uffe1",  # pound sign
    (0x22, 0x4C): "\uffe2",  # not sign
}


def verify(grid):
    """Every Shift-JIS pair must land on the same character, cell for cell.

    Only the pairs the CP932 codec maps to a single BMP character are checked.
    The NEC/IBM extension rows (13, 89-92 in JIS terms) are outside the
    standard grid, and the six glyph variants above are differences of
    rendering rather than of the grid.
    """
    failures = 0
    checked = 0
    for lead in list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD)):
        for trail in list(range(0x40, 0x7F)) + list(range(0x80, 0xFD)):
            try:
                text = bytes([lead, trail]).decode("cp932")
            except UnicodeDecodeError:
                continue
            if len(text) != 1:
                continue
            row_cell = sjis_row_cell(lead, trail)
            if row_cell is None:
                continue
            row, cell = row_cell
            grid_text = grid.get((row, cell))
            if grid_text is None:
                continue
            checked += 1
            if grid_text != text and GLYPH_VARIANTS.get((row, cell)) != text:
                failures += 1
                if failures <= 20:
                    print("  %02X %02X: grid %r, CP932 %r" % (lead, trail, grid_text, text),
                          file=sys.stderr)
    return checked, failures


def sjis_row_cell(lead, trail):
    """Shift-JIS pair -> (row, cell); the same arithmetic as metadata.c."""
    if 0x81 <= lead <= 0x9F:
        row = (lead - 0x81) * 2 + 0x21
    elif 0xE0 <= lead <= 0xFC:
        row = (lead - 0xC1) * 2 + 0x21
    else:
        return None
    if 0x40 <= trail <= 0x7E:
        cell = trail - 0x1F
    elif 0x80 <= trail <= 0x9E:
        cell = trail - 0x20
    elif 0x9F <= trail <= 0xFC:
        row += 1
        cell = trail - 0x7E
    else:
        return None
    if not (0x21 <= row <= 0x7E and 0x21 <= cell <= 0x7E):
        return None
    return row, cell


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="exit 1 when the checked-in table no longer matches")
    parser.add_argument("--output", default=None, help="path to write (default: beside this script)")
    args = parser.parse_args()

    grid = build_grid()
    text, cells, pool_bytes = render(grid)
    checked, failures = verify(grid)
    if failures:
        print("gen_jis_table: Shift-JIS disagrees with the grid in %d of %d pairs"
              % (failures, checked), file=sys.stderr)
        return 1

    import os
    path = args.output or os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                       "..", "src", "system", "library", "jisx0208.c")
    path = os.path.normpath(path)
    if args.check:
        try:
            with open(path, "r", encoding="utf-8") as handle:
                current = handle.read()
        except FileNotFoundError:
            print("gen_jis_table: %s is missing" % path, file=sys.stderr)
            return 1
        if current != text:
            print("gen_jis_table: %s is out of date; run tools/gen_jis_table.py" % path,
                  file=sys.stderr)
            return 1
        print("gen_jis_table: %s is current (%d cells, %d bytes of text)"
              % (os.path.relpath(path), cells, pool_bytes))
        return 0

    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print("gen_jis_table: wrote %s (%d cells, %d bytes of text, %d pairs cross-checked)"
          % (os.path.relpath(path), cells, pool_bytes, checked))
    return 0


if __name__ == "__main__":
    sys.exit(main())
