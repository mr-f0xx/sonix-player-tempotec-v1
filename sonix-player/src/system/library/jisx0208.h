#ifndef JISX0208_H
#define JISX0208_H

#include <stdint.h>

// JIS X 0208, the character set both Shift-JIS and EUC-JP address.
//
// A tag that says nothing about its encoding -- every ID3v1 tag, and an
// ID3v2 frame whose encoding byte is 0x00 -- is read by the tagger's own
// machine as often as not, and a Japanese Windows wrote Shift-JIS there. The
// bytes then arrive as Latin-1, which turns "宇多田ヒカル" into "F½c q J" and
// files the artist under F. Shift-JIS and EUC-JP are two ways of naming one
// grid of characters: 94 rows of 94 cells (0x21..0x7E each), which this table
// holds as UTF-8 so either encoding can be read with a single lookup.
//
// Generated by tools/gen_jis_table.py, which also checks the Shift-JIS
// arithmetic in metadata.c against the CP932 codec: every pair that codec
// knows must land on the character the grid holds.
//
// JIS_OFFSETS has one entry per cell, row 0x21 first and cell 0x21 first
// inside a row. Zero means the cell holds nothing (the standard never filled
// every cell). Anything else is the offset of the cell's character in
// JIS_POOL, which is a UTF-8 string, NUL-terminated, and never contains a NUL
// of its own: a cell's text is (const char *)JIS_POOL + JIS_OFFSETS[i], cast
// once because the pool is bytes.

#define JIS_GRID_FIRST 0x21
#define JIS_GRID_LAST 0x7E
#define JIS_GRID_ROWS (JIS_GRID_LAST - JIS_GRID_FIRST + 1)   // 94
#define JIS_GRID_CELLS (JIS_GRID_ROWS * JIS_GRID_ROWS)       // 8836

extern const unsigned char JIS_POOL[];
extern const uint16_t JIS_OFFSETS[JIS_GRID_CELLS];

#endif // JISX0208_H
